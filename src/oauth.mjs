import http from "node:http";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { exec } from "node:child_process";

const WINDSURF_AUTH_BASE_URL = "https://www.windsurf.com";
const WINDSURF_REGISTER_API_BASE_URL = "https://register.windsurf.com";
const WINDSURF_CLIENT_ID = "3GUryQ7ldAeKEuD2obYnppsnmj58eP5u";
const OAUTH_TIMEOUT_MS = 5 * 60 * 1000;

function randomToken() {
  return crypto.randomBytes(24).toString("base64url");
}

function safeJsonParse(s) {
  try {
    return JSON.parse(s);
  } catch {
    return null;
  }
}

function openUrl(url) {
  const plat = os.platform();
  const escapedUrl = url.replace(/"/g, '\\"');
  if (plat === "win32") {
    exec(`start "" "${escapedUrl}"`);
  } else if (plat === "darwin") {
    exec(`open "${escapedUrl}"`);
  } else {
    exec(`xdg-open "${escapedUrl}"`);
  }
}

export function getDefaultCredentialsPath() {
  const plat = os.platform();
  const home = os.homedir();
  if (plat === "win32") {
    const appdata = process.env.APPDATA || path.join(home, "AppData", "Roaming");
    return path.join(appdata, "devin", "credentials.toml");
  }
  return path.join(home, ".devin", "credentials.toml");
}

export function saveApiKeyToToml(apiKey, targetPath = getDefaultCredentialsPath()) {
  const dir = path.dirname(targetPath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  let content = "";
  if (fs.existsSync(targetPath)) {
    content = fs.readFileSync(targetPath, "utf-8");
  }

  const keyLine = `windsurf_api_key = "${apiKey}"`;
  if (/^\s*windsurf_api_key\s*=/m.test(content)) {
    content = content.replace(/^\s*windsurf_api_key\s*=.*$/m, keyLine);
  } else if (/^\s*devin_api_key\s*=/m.test(content)) {
    content = content.replace(/^\s*devin_api_key\s*=.*$/m, keyLine);
  } else {
    content = content.trimEnd() ? `${content.trimEnd()}\n${keyLine}\n` : `# Generated by devin-search-mcp OAuth login\n${keyLine}\n`;
  }

  fs.writeFileSync(targetPath, content, "utf-8");
  return targetPath;
}

