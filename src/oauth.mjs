function createOAuthCallbackServer() {
  return new Promise((resolve, reject) => {
    const state = randomToken();
    let server = null;
    let timer = null;
    let tokenResolve = null;
    let tokenReject = null;

    const tokenPromise = new Promise((res, rej) => {
      tokenResolve = res;
      tokenReject = rej;
    });

    const close = () => {
      if (timer) clearTimeout(timer);
      try {
        server?.close();
      } catch {}
    };

    const finish = (err, accessToken) => {
      close();
      if (err) {
        tokenReject?.(err);
      } else {
        tokenResolve?.(accessToken || "");
      }
    };

    server = http.createServer((req, res) => {
      const host = req.headers.host || "127.0.0.1";
      const url = new URL(req.url || "/", `http://${host}`);
      if (url.pathname !== "/windsurf-auth-callback") {
        res.writeHead(404);
        res.end("Not Found");
        return;
      }

      const gotState = url.searchParams.get("state") || "";
      const error = url.searchParams.get("error") || "";
      const errorDescription = url.searchParams.get("error_description") || "";
      const accessToken = url.searchParams.get("access_token") || "";

      if (gotState !== state) {
        res.writeHead(400, { "Content-Type": "text/html; charset=utf-8" });
        res.end(renderHtml(false, "授权验证失败", "OAuth state 参数校验不匹配，请返回终端重新发起登录。"));
        finish(new Error("OAuth state 参数校验失败"));
        return;
      }

      if (error) {
        const msg = errorDescription ? `${error} (${errorDescription})` : error;
        res.writeHead(400, { "Content-Type": "text/html; charset=utf-8" });
        res.end(renderHtml(false, "授权失败", `平台返回错误: ${msg}`));
        finish(new Error(`授权被拒绝: ${msg}`));
        return;
      }

      if (!accessToken.trim()) {
        res.writeHead(400, { "Content-Type": "text/html; charset=utf-8" });
        res.end(renderHtml(false, "授权未完成", "未接收到访问凭证，请重试。"));
        finish(new Error("回调缺少 access_token"));
        return;
      }

      res.writeHead(200, { "Content-Type": "text/html; charset=utf-8" });
      res.end(renderHtml(true, "🎉 授权成功！", "Devin 凭证已成功接收，正在本地保存。你可以关闭本页面，返回终端查看结果。"));
      finish(null, accessToken);
    });

    server.on("error", (err) => finish(err instanceof Error ? err : new Error(String(err))));

    server.listen(0, "127.0.0.1", () => {
      const addr = server?.address();
      if (!addr || typeof addr === "string") {
        reject(new Error("无法获取本地 OAuth 端口"));
        return;
      }

      const redirectUri = `http://127.0.0.1:${addr.port}/windsurf-auth-callback`;
      const params = new URLSearchParams();
      params.set("response_type", "token");
      params.set("client_id", WINDSURF_CLIENT_ID);
      params.set("redirect_uri", redirectUri);
      params.set("state", state);
      params.set("prompt", "login");
      params.set("redirect_parameters_type", "query");
      params.set("workflow", "onboarding");

      const authUrl = `${WINDSURF_AUTH_BASE_URL}/windsurf/signin?${params.toString()}`;
      timer = setTimeout(() => finish(new Error("等待浏览器授权超时 (5分钟)")), OAUTH_TIMEOUT_MS);

      resolve({ authUrl, tokenPromise, close });
    });
  });
}

export async function exchangeFirebaseToken(firebaseIdToken) {
  const resp = await fetch(
    `${WINDSURF_REGISTER_API_BASE_URL}/exa.seat_management_pb.SeatManagementService/RegisterUser`,
    {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Accept: "application/json",
        "Connect-Protocol-Version": "1",
      },
      body: JSON.stringify({ firebase_id_token: firebaseIdToken }),
      signal: AbortSignal.timeout(20000),
    }
  );

  if (!resp.ok) {
    const text = await resp.text();
    const parsed = safeJsonParse(text);
    throw new Error(`RegisterUser 失败 HTTP ${resp.status}: ${parsed?.message || text.slice(0, 150)}`);
  }

  const data = await resp.json();
  const apiKey = data.api_key || data.apiKey;
  if (!apiKey) {
    throw new Error("RegisterUser 成功响应但未包含 api_key 字段");
  }

  return {
    apiKey,
    name: data.name || "",
    email: data.email || "",
  };
}

